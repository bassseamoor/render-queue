'use strict';

const MARKER='MOOR:AUTO-RELEASE';
const BLOCKED_EXACT=new Set([
  'FUNNEL.md',
  'BUSTER.md',
  'worker-response-sop.json',
  'funnel-kernel.js',
  '.github/workflows/moor-auto-release.yml'
]);
const BLOCKED_PREFIX=[
  'moor-spec/',
  'funnel-law-',
  'funnel-receipt-core',
  'funnel-capability-core',
  'funnel-budget-core',
  'funnel-consensus-core',
  'funnel-case-runtime',
  'funnel-society-core',
  '.github/workflows/'
];

function parse(body){
  const s=String(body||'');
  const m=s.match(/<!--\s*MOOR:AUTO-RELEASE\s*([\s\S]*?)-->/i);
  if(!m)return {enabled:false,metadata:null,error:null};
  const raw=String(m[1]||'').trim();
  if(!raw)return {enabled:true,metadata:{release_mode:'auto'},error:null};
  try{
    const metadata=JSON.parse(raw);
    return {enabled:true,metadata,error:null};
  }catch(e){
    return {enabled:false,metadata:null,error:'invalid auto-release JSON: '+e.message};
  }
}
function blockedPath(path){
  path=String(path||'');
  if(BLOCKED_EXACT.has(path))return true;
  return BLOCKED_PREFIX.some(p=>path.startsWith(p));
}
function evaluatePaths(paths){
  const blocked=(paths||[]).filter(blockedPath);
  return {ok:blocked.length===0,blocked};
}
function metadataValid(meta){
  const m=meta&&typeof meta==='object'?meta:{};
  const errors=[];
  if(m.release_mode!=='auto')errors.push('release_mode must be "auto"');
  if(!String(m.item_id||'').trim())errors.push('item_id required');
  if(!String(m.destination||'').trim())errors.push('destination required');
  return {ok:errors.length===0,errors};
}
function workflowGate(runs){
  const list=(runs||[]).filter(r=>r&&r.name!=='MOOR Auto Release');
  const prRuns=list.filter(r=>r.event==='pull_request');
  const recovery=prRuns.filter(r=>r.name==='Pulse recovery checks');
  if(!recovery.length)return {ready:false,reason:'waiting for Pulse recovery checks',failed:[],pending:[]};
  const pending=prRuns.filter(r=>['queued','in_progress','waiting','requested','pending'].includes(String(r.status||'')));
  if(pending.length)return {ready:false,reason:'checks still running',failed:[],pending:pending.map(x=>x.name)};
  const badConclusions=new Set(['failure','cancelled','timed_out','action_required','startup_failure','stale']);
  const failed=prRuns.filter(r=>r.status==='completed'&&badConclusions.has(String(r.conclusion||'')));
  if(failed.length)return {ready:false,reason:'checks failed',failed:failed.map(x=>x.name),pending:[]};
  const latestRecovery=recovery.sort((a,b)=>String(b.updated_at||'').localeCompare(String(a.updated_at||'')))[0];
  if(latestRecovery.conclusion!=='success')return {ready:false,reason:'Pulse recovery not successful',failed:[latestRecovery.name],pending:[]};
  return {ready:true,reason:'all observed PR workflows green',failed:[],pending:[]};
}
function safeId(x){
  return String(x||'item').toLowerCase().replace(/[^a-z0-9._-]+/g,'-').replace(/^-+|-+$/g,'').slice(0,80)||'item';
}
function dateStamp(iso){
  const d=iso?new Date(iso):new Date();
  return Number.isNaN(d.getTime())?new Date().toISOString().slice(0,10):d.toISOString().slice(0,10);
}
function receipt({pr,metadata,mergeSha,workflowRuns,at}){
  const when=at||new Date().toISOString();
  return {
    schema:'moor.dev-feed-event',
    version:1,
    event_id:'auto-release-pr-'+pr.number+'-'+String(mergeSha||'').slice(0,12),
    item_id:String(metadata.item_id),
    title:pr.title,
    kind:'auto-release',
    stage:'main',
    status:'complete',
    at:when,
    source:'MOOR Auto Release / PR #'+pr.number,
    worker:pr.user&&pr.user.login||'github-worker',
    destination:metadata.destination,
    detail:'Eligible same-repo PR passed observed CI gates and was squash-merged automatically. Receipt generated by trusted main-branch workflow.',
    refs:[pr.html_url,mergeSha].filter(Boolean),
    receipt:{
      pull_request:pr.number,
      merge_sha:mergeSha,
      automation:'moor-auto-release-v1',
      funnel_receipt_ref:metadata.funnel_receipt_ref||null
    },
    stats:{
      observed_workflows:(workflowRuns||[]).filter(r=>r.event==='pull_request'&&r.name!=='MOOR Auto Release').map(r=>({name:r.name,status:r.status,conclusion:r.conclusion}))
    }
  };
}
function trajectoryCheckpoint({pr,metadata,mergeSha,at}){
  const t=metadata&&metadata.trajectory;
  if(!t||typeof t!=='object')return null;
  for(const k of ['original_intent','funnel_intent','built_result'])if(!String(t[k]||'').trim())return null;
  return {
    schema:'moor.trajectory-checkpoint',
    version:1,
    checkpoint_id:'auto-release-pr-'+pr.number,
    at:at||new Date().toISOString(),
    source:'repository-canonical-auto-release',
    title:t.title||pr.title,
    originalIntent:t.original_intent,
    funnelIntent:t.funnel_intent,
    builtResult:t.built_result,
    artifact:mergeSha,
    destination:metadata.destination,
    refs:[pr.html_url,mergeSha].filter(Boolean),
    assessors:[]
  };
}
module.exports=Object.freeze({
  MARKER,BLOCKED_EXACT,BLOCKED_PREFIX,parse,blockedPath,evaluatePaths,metadataValid,workflowGate,safeId,dateStamp,receipt,trajectoryCheckpoint
});